    def _build_seedance_prompt(self, shot: dict, preset: StylePreset) -> str:
        """Compose the Seedance prompt from action + style preset motion descriptor.

        Dialog is already embedded in shot.action by the timeline writer
        (P08b convention), so the action field is the single source of truth
        for what Seedance should produce.
        """
        motion_descriptor = (getattr(preset, "motion_descriptor", "") or "").strip()
        action = shot["action"].strip()
        camera = (shot.get("camera") or "").strip()

        parts = [action]
        if camera and camera.lower() not in action.lower():
            parts.append(f"Camera: {camera}.")
        if motion_descriptor:
            parts.append(motion_descriptor)
        parts.append(
            "Maintain perfect character consistency with the input reference "
            "image throughout the entire clip. No on-screen text. No watermarks."
        )
        return " ".join(parts)

    def _over_budget(self, project_id: str) -> bool:
        proj = db.get_project(project_id)
        if proj is None:
            return False
        return float(proj.get("total_cost_usd") or 0) >= self.budget_limit

    def _fresh_cost(self, project_id: str) -> float:
        proj = db.get_project(project_id)
        return float(proj.get("total_cost_usd") or 0) if proj else 0.0

    def _sweep_orphan_jobs(self, project_id: str) -> None:
        """Mark any 'running' generation_jobs and 'rendering' shots for this
        project as cancelled / pending. Called at render entry to recover
        from prior crashes where a process died mid-job.
        """
        rows = db.list_jobs(project_id=project_id, status="running")
        for row in rows:
            db.mark_job_cancelled(
                row["id"], reason="orphan from prior crashed run",
            )
            logger.warning(
                "orphan job marked cancelled: %s (project=%s, type=%s)",
                row["id"], project_id, row.get("job_type"),
            )
        for s in db.list_shots(project_id):
            if s.get("render_status") == "rendering":
                db.update_shot(
                    s["id"],
                    render_status="pending",
                    render_error="orphan from prior crashed run",
                )

    def _save_partial_zip(
        self,
        project_id: str,
        results: list[ShotResult],
    ) -> Path:
        partial_dir = PROJECTS_ROOT / project_id / "output" / PARTIAL_OUTPUT_DIRNAME
        partial_dir.mkdir(parents=True, exist_ok=True)
        zip_path = partial_dir / f"shots_{int(time.time())}.zip"
        try:
            with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
                for r in results:
                    if r.video_path and r.video_path.exists():
                        z.write(
                            r.video_path,
                            arcname=f"shot_{r.ordinal:02d}_{r.shot_id}.mp4",
                        )
            logger.info("saved partial zip: %s", zip_path)
        except (OSError, zipfile.BadZipFile) as e:
            logger.error("failed to write partial zip: %s", e)
        return zip_path

    async def _mark_failed(self, project_id: str, error: str) -> None:
        db.update_project(
            project_id, phase="failed", error_message=error[:500],
        )
        await PROGRESS_BUS.emit(ProgressEvent(
            project_id=project_id, timestamp=time.time(),
            stage="failed", detail=error[:200], error=error,
        ))
        logger.error("render failed project=%s: %s", project_id, error)

    async def _mark_cancelled(self, project_id: str, detail: str) -> None:
        # Leave phase='render' so a re-run resumes; error_message documents why.
        db.update_project(
            project_id,
            error_message=f"cancelled: {detail}"[:500],
        )
        for row in db.list_jobs(project_id=project_id, status="running"):
            db.mark_job_cancelled(row["id"], reason="render cancelled by user")
        await PROGRESS_BUS.emit(ProgressEvent(
            project_id=project_id, timestamp=time.time(),
            stage="cancelled", detail=detail,
        ))
        logger.warning("render cancelled project=%s: %s", project_id, detail)

    async def _watchdog(
        self,
        project_id: str,
        cancel_flag: asyncio.Event,
    ) -> None:
        """Set the cancellation flag if render exceeds max_render_seconds."""
        try:
            await asyncio.sleep(self.max_render_seconds)
            if not cancel_flag.is_set():
                logger.warning(
                    "watchdog firing: render exceeded %ds for project %s",
                    self.max_render_seconds, project_id,
                )
                cancel_flag.set()
                await PROGRESS_BUS.emit(ProgressEvent(
                    project_id=project_id, timestamp=time.time(),
                    stage="cancelled",
                    detail=f"watchdog: render exceeded {self.max_render_seconds}s",
                ))
        except asyncio.CancelledError:
            pass


