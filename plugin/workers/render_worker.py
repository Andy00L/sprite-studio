"""Sprite Studio render worker.

Takes a project in phase='render', orchestrates Seedance shot generation,
ElevenLabs narration (conditional on use_narrator), music pick, and ffmpeg
final stitch. Produces final_video_path.

Architecture (P08b-aware):
- Each shot's audio is generated by Seedance natively (has_dialog flag).
- ElevenLabs only produces narrator voice-over, only when use_narrator=True.
- ffmpeg ducks narrator volume during dialog shots (compute_dialog_windows).

Concurrency:
- Up to MAX_SHOT_CONCURRENCY shot renders in flight (default 4).
- Narration runs in parallel with shots (single task).
- Music pick runs as a fast separate sync task.

Resilience:
- One failed shot does not abort the project. Stitch proceeds with N-1
  shots if at least 1 shot + (narration if use_narrator) succeeded.
- On startup, orphan 'running' jobs from prior crashes are marked
  'cancelled' so the worker re-attempts them.
- KeyboardInterrupt / cancellation flag --> mark in-flight jobs cancelled,
  leave project in phase='render' for resume.

Cost guard:
- BUDGET_HARD_LIMIT_USD checked before each paid call.
- Cost mutation is owned by the service clients (seedance.image_to_video and
  elevenlabs.synthesize_narration call db.increment_project_cost).

Progress signaling:
- A per-project ProgressBus publishes ProgressEvent objects.
- /sprite_status reads the latest event for the project via latest_progress().
"""
