class OrchestratorRenderError(RuntimeError):
    """Programmer error raised by render_project for unknown / wrong-phase
    projects. The orchestrator catches and surfaces a friendly message;
    this is never raised for in-flight provider failures.
    """


async def cancel_render(project_id: str) -> None:
    """Signal the running render for project_id to cancel cooperatively."""
    await CANCELLATION_REGISTRY.signal(project_id)


def latest_progress(project_id: str) -> Optional[dict]:
    """Read-only view for /sprite_status. Returns dict or None."""
    ev = PROGRESS_BUS.latest(project_id)
    if ev is None:
        return None
    return asdict(ev)
